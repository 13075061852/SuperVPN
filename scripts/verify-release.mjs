import fs from 'node:fs/promises';
import path from 'node:path';
import { createReadStream } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const yaml = require('js-yaml'), asar = require('@electron/asar');
const directory = path.resolve(process.argv[2] || 'release');
const pkg = JSON.parse(await fs.readFile(new URL('../package.json', import.meta.url), 'utf8'));
const metadata = yaml.load(await fs.readFile(path.join(directory, 'latest.yml'), 'utf8'));
const expected = `SuperVPN-Setup-${pkg.version}.exe`;
if (metadata.version !== pkg.version || metadata.path !== expected) throw new Error('Release version/path mismatch');
const installer = path.join(directory, expected), header = await fs.open(installer, 'r');
try { const bytes = Buffer.alloc(2); await header.read(bytes, 0, 2, 0); if (bytes.toString() !== 'MZ') throw new Error('Invalid installer'); } finally { await header.close(); }
const hash = createHash('sha512'); for await (const chunk of createReadStream(installer)) hash.update(chunk);
if (hash.digest('base64') !== metadata.sha512) throw new Error('Installer hash mismatch');
if (metadata.files?.[0]?.sha512 !== metadata.sha512 || metadata.files[0].size !== (await fs.stat(installer)).size) throw new Error('Update file metadata mismatch');
await fs.access(installer + '.blockmap');
const resources = path.join(directory, 'win-unpacked', 'resources');
const config = yaml.load(await fs.readFile(path.join(resources, 'app-update.yml'), 'utf8'));
if (config.provider !== 'github' || config.owner !== '13075061852' || config.repo !== 'SuperVPN' || config.private === true || config.token) throw new Error('Unexpected/private update feed');
const archive = path.join(resources, 'app.asar');
const packed = JSON.parse(asar.extractFile(archive, 'package.json').toString());
if (packed.version !== pkg.version || !packed.dependencies['electron-updater']) throw new Error('Packaged updater/version missing');
for (const file of ['electron/main.cjs', 'desktop/updates.cjs', 'desktop/update-integrity.cjs', 'electron/tray.ico']) if (!asar.extractFile(archive, file).length) throw new Error('Missing app file');
const files = asar.listPackage(archive);
if (files.some(file => /(?:^|[\\/])(?:\.env[^\\/]*|state\.bin|proxy-recovery\.json|\.git|id_rsa|[^\\/]*\.(?:pfx|p12))(?:[\\/]|$)/i.test(file))) throw new Error('Private runtime data in app archive');
for (const file of ['sing-box.exe', 'LICENSE-sing-box', 'LICENSE-GPL-3.0.txt', 'LICENSE-source.txt']) await fs.access(path.join(resources, 'core', file));
console.log(JSON.stringify({ version: pkg.version, installer: expected, bytes: (await fs.stat(installer)).size, sha512Verified: true, updateFeed: `${config.owner}/${config.repo}`, privateDataExcluded: true }));
